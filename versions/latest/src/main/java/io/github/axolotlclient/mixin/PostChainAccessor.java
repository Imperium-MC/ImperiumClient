package io.github.axolotlclient.mixin;

import java.util.Map;

import com.mojang.blaze3d.pipeline.RenderTarget;
import net.minecraft.client.renderer.PostChain;
import net.minecraft.resources.Identifier;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.gen.Accessor;

/**
 * Exposes a post chain's persistent render targets so the HUD blur chain can hand the blurred
 * frame to GUI blits (the persistent {@code blurred} target of {@code axolotlclient:hud_blur}).
 */
@Mixin(PostChain.class)
public interface PostChainAccessor {

	@Accessor("persistentTargets")
	Map<Identifier, RenderTarget> axolotlclient$persistentTargets();
}
